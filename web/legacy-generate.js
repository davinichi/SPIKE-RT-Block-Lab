import {validateProgram, IMAGES, VERSION} from './model.js';

export function generatePython(program) {
  const {devices} = validateProgram(program);
  const motors = [...devices].filter(([,kind]) => kind === 'motor').map(([p]) => p);
  const lines = [
    `# SPIKE Block Lab ${VERSION} / SPIKE App 3 Hub OS`,
    '# Hardware verification pending. All logic runs on the hub.',
    'import runloop', 'import motor', 'import distance_sensor',
    'from hub import port, light_matrix', '', 'async def main():', '    try:'
  ];
  const emit = (depth, text) => lines.push('    '.repeat(depth) + text);
  let loop = 0;
  function seq(body, depth) {
    if (!body.length) emit(depth, 'pass');
    for (const b of body) {
      if (b.id) emit(depth, `# block: ${String(b.id).replace(/[^a-zA-Z0-9_-]/g,'')}`);
      switch (b.type) {
        case 'image':
          for (let r=0;r<5;r++) for (let c=0;c<5;c++) emit(depth, `light_matrix.set_pixel(${c}, ${r}, ${IMAGES[b.image][r][c] === '1' ? 100 : 0})`);
          break;
        case 'wait': emit(depth, `await runloop.sleep_ms(${Math.round(b.seconds*1000)})`); break;
        case 'motor':
          emit(depth, `motor.run(port.${b.port}, ${b.speed})`);
          emit(depth, `await runloop.sleep_ms(${Math.round(b.seconds*1000)})`);
          emit(depth, `motor.stop(port.${b.port})`); break;
        case 'repeat':
          emit(depth, `for repeat_${loop++} in range(${b.count}):`); seq(b.body,depth+1);
          emit(depth+1,'await runloop.sleep_ms(10)'); break;
        case 'forever':
          emit(depth,'while True:'); seq(b.body,depth+1); emit(depth+1,'await runloop.sleep_ms(10)'); break;
        case 'ifDistance':
          emit(depth, `distance_mm = distance_sensor.distance(port.${b.port})`);
          emit(depth, `if distance_mm is not None and distance_mm >= 0 and distance_mm < ${Math.round(b.cm*10)}:`);
          seq(b.then,depth+1); emit(depth,'else:'); seq(b.else,depth+1); break;
      }
    }
  }
  seq(program.body,2);
  emit(1,'finally:');
  if (!motors.length) emit(2,'pass');
  for (const p of motors) {
    emit(2,'try:'); emit(3,`motor.stop(port.${p})`); emit(2,'except Exception:'); emit(3,'pass');
  }
  lines.push('', 'runloop.run(main())', '');
  return lines.join('\n');
}

// C generator uses a cooperative wait helper so every wait also checks Stop.
export function generateC(program) {
  const {devices} = validateProgram(program);
  const motors = [...devices].filter(([,k]) => k === 'motor').map(([p]) => p);
  const distances = [...devices].filter(([,k]) => k === 'distance').map(([p]) => p);
  const lines = [
    `/* Generated by SPIKE Block Lab ${VERSION}. Target: SPIKE-RT v0.2.0. */`,
    '#include <kernel.h>', '#include <stdint.h>', '#include <stdbool.h>', '#include <stddef.h>',
    '#include <t_syslog.h>', '#include "kernel_cfg.h"', '#include "app.h"',
    '#include <spike/hub/button.h>', '#include <spike/hub/display.h>',
    '#include <spike/pup/motor.h>', '#include <spike/pup/ultrasonicsensor.h>', '',
    ...motors.map(p => `static pup_motor_t *motor_${p};`),
    ...distances.map(p => `static pup_device_t *distance_${p};`),
    'static bool failed = false;', 'static bool armed = false;', '',
    'static void stop_all(void) {',
    ...motors.map(p => `    if (motor_${p}) (void)pup_motor_brake(motor_${p});`), '}',
    'static bool check_error(pbio_error_t err) {',
    '    if (err == PBIO_SUCCESS) return true;',
    '    failed = true; stop_all(); syslog(LOG_ERROR, "Device error: %d", (int)err); return false;', '}',
    'static bool keep_running(void) {',
    '    hub_button_t buttons = 0;',
    '    if (failed || !check_error(hub_button_is_pressed(&buttons))) return false;',
    '    if (armed && (buttons & HUB_BUTTON_CENTER)) { failed = true; stop_all(); return false; }',
    '    return true;', '}',
    'static bool wait_ms(uint32_t ms) {',
    '    while (ms > 0) {',
    '        if (!keep_running()) return false;',
    '        uint32_t step = ms > 10 ? 10 : ms;',
    '        if (dly_tsk(step * 1000U) != E_OK) { failed = true; stop_all(); return false; }',
    '        ms -= step;',
    '    }',
    '    return keep_running();', '}',
    'static bool await_start(void) {',
    '    hub_button_t buttons = 0;',
    '    /* Wait for a new center-button press, then release. */',
    '    for (int stage = 0; stage < 3; ++stage) {',
    '        do {',
    '            if (!check_error(hub_button_is_pressed(&buttons)) || !wait_ms(10)) return false;',
    '        } while (((buttons & HUB_BUTTON_CENTER) != 0) != (stage == 1));',
    '    }',
    '    armed = true; return true;', '}',
    ...distances.flatMap(p => [
      `static bool near_${p}(int32_t limit_mm) {`,
      `    int32_t mm = pup_ultrasonic_sensor_distance(distance_${p});`,
      '    /* No target / invalid reading is never treated as zero distance. */',
      '    return mm >= 0 && mm < limit_mm;', '}'
    ]),
    'void main_task(intptr_t exinf) {', '    (void)exinf;',
    '    /* Let the device drivers start before acquiring ports. */',
    '    if (!wait_ms(3000)) goto cleanup;'
  ];
  for (const p of motors) lines.push(
    `    motor_${p} = pup_motor_get_device(PBIO_PORT_ID_${p});`,
    `    if (!motor_${p}) { failed = true; goto cleanup; }`,
    '    {', '        pbio_error_t err = PBIO_ERROR_AGAIN;',
    '        for (int attempt = 0; attempt < 200; ++attempt) {',
    `            err = pup_motor_setup(motor_${p}, PUP_DIRECTION_CLOCKWISE, true);`,
    '            if (err != PBIO_ERROR_AGAIN) break;',
    '            if (!wait_ms(10)) goto cleanup;', '        }',
    '        if (!check_error(err)) goto cleanup;', '    }'
  );
  for (const p of distances) lines.push(
    `    distance_${p} = pup_ultrasonic_sensor_get_device(PBIO_PORT_ID_${p});`,
    `    if (!distance_${p}) { failed = true; goto cleanup; }`
  );
  lines.push('    syslog(LOG_NOTICE, "READY: press and release center button");', '    if (!await_start()) goto cleanup;');
  const emit = (d,s) => lines.push('    '.repeat(d)+s);
  let counter = 0;
  function seq(body,d) {
    for (const b of body) {
      if (b.id) emit(d,`/* block: ${String(b.id).replace(/[^a-zA-Z0-9_-]/g,'')} */`);
      emit(d,'if (!keep_running()) goto cleanup;');
      switch (b.type) {
        case 'image': {
          const pixels = IMAGES[b.image].join('').split('').map(x=>x==='1'?100:0);
          emit(d,`{ uint8_t image[25] = {${pixels.join(',')}};`);
          emit(d+1,'if (!check_error(hub_display_image(image))) goto cleanup;'); emit(d,'}'); break;
        }
        case 'wait': emit(d,`if (!wait_ms(${Math.round(b.seconds*1000)}U)) goto cleanup;`); break;
        case 'motor':
          emit(d,`if (!check_error(pup_motor_set_speed(motor_${b.port}, ${b.speed}))) goto cleanup;`);
          emit(d,`if (!wait_ms(${Math.round(b.seconds*1000)}U)) goto cleanup;`);
          emit(d,`if (!check_error(pup_motor_brake(motor_${b.port}))) goto cleanup;`); break;
        case 'repeat': {
          const id = counter++; emit(d,`for (int repeat_${id} = 0; repeat_${id} < ${b.count}; ++repeat_${id}) {`);
          seq(b.body,d+1); emit(d+1,'if (!wait_ms(10)) goto cleanup;'); emit(d,'}'); break;
        }
        case 'forever': emit(d,'while (keep_running()) {'); seq(b.body,d+1); emit(d+1,'if (!wait_ms(10)) goto cleanup;'); emit(d,'}'); break;
        case 'ifDistance': emit(d,`if (near_${b.port}(${Math.round(b.cm*10)})) {`); seq(b.then,d+1); emit(d,'} else {'); seq(b.else,d+1); emit(d,'}'); break;
      }
    }
  }
  seq(program.body,1);
  lines.push('cleanup:', '    stop_all();', '    syslog(LOG_NOTICE, failed ? "STOPPED / ERROR" : "DONE");', '    ext_tsk();', '}', '');
  return lines.join('\n');
}
export function generateRTProject(program, cdl) {
  if (typeof cdl !== 'string' || !cdl.includes('kernel.cdl')) throw Error('SPIKE-RT構成テンプレートを読み込めませんでした。');
  return {
    'app.c': generateC(program),
    'app.h': '#ifndef SPIKE_LAB_APP_H\n#define SPIKE_LAB_APP_H\n#include <kernel.h>\n#define MAIN_PRIORITY 5\n#define MAIN_STACK_SIZE 4096\n#ifndef TOPPERS_MACRO_ONLY\nextern void main_task(intptr_t exinf);\n#endif\n#endif\n',
    'app.cfg': 'INCLUDE("tecsgen.cfg");\n#include "app.h"\nCRE_TSK(APP_MAIN_TASK, { TA_ACT, 0, main_task, MAIN_PRIORITY, MAIN_STACK_SIZE, NULL });\n',
    'app.cdl': cdl,
    'program.json': JSON.stringify(program,null,2)+'\n',
    'README.txt': 'SPIKE Block Lab / SPIKE-RT v0.2.0\n\nCopy this directory to spike-rt/user_apps/app.\nUse the official SPIKE-RT build environment. See BUILD.md.\nThe hub waits for a center-button press and release before running.\nPress center again to stop. All logic runs on the hub.\nHardware testing is pending.\n',
    'BUILD.md': RT_BUILD,
    'target.json': JSON.stringify({generator:VERSION,target:'SPIKE-RT',ref:'v0.2.0',entry:'main_task',name:'app',hardwareTested:false},null,2)+'\n'
  };
}
